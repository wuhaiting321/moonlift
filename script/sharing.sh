#!/usr/bin/env bash
# Shared imports: one external instance, several import entries.
#
#   bash script/sharing.sh
#
# What this checks, and why it is a script of its own rather than a case inside
# `verify.sh`:
#
#   1. Two import entries that name the same `(module, name)` are one cell:
#      a write through `$a` is visible through `$b` in the generated package.
#   2. Binding replaces the stand-in: the host hands over `Ref(5)`, the generated
#      code reads 5, and a defined global initialised from an imported one takes
#      the bound value at init.
#   3. Binding is not pre-filling: a fresh, zeroed memory handed to
#      `moonlift_bind()` receives the module's data segments in
#      `moonlift_init()`. Nothing has to be written into it beforehand.
#
# `verify.sh` compares one call at a time against Node; this one asserts
# properties of the binding model itself, which no single call can observe.
#
# Each unbound case gets a package of its own, because binding is process state:
# a test that asserts the default must not run after a test that binds.
set -uo pipefail

cd "$(dirname "$0")/.." || exit 1

tmp=/tmp/moonlift_sharing
rm -rf "$tmp"
mkdir -p "$tmp"

cli() { moon run cmd/main --target "${TARGET:-wasm-gc}" -- "$@" 2>/dev/null; }

pass=0
fail=0
ok() {
  printf 'ok   %-56s %s\n' "$1" "$2"
  pass=$((pass + 1))
}
no() {
  printf 'FAIL %-56s %s\n' "$1" "$2"
  fail=$((fail + 1))
}

# run_case <label> <fixture> <dir-name> <test-file> <expectation>
run_case() {
  local label="$1" fixture="$2" name="$3" body="$4"
  local dir="$tmp/$name"
  mkdir -p "$dir"
  if ! cli decompile "corpus/good/$fixture.wasm" -o "$dir" > "$dir.log" 2>&1; then
    no "$label" "decompile failed, see $dir.log"
    return
  fi
  printf '%s\n' "$body" > "$dir/sharing_wbtest.mbt"
  if ( cd "$dir" && moon test --target "${TARGET:-wasm-gc}" > test.log 2>&1 ); then
    ok "$label" "$(grep -E '^Total tests' "$dir/test.log" | head -1)"
  else
    no "$label" "see $dir/test.log"
  fi
}

# --- case 1: the same mutable global imported twice ------------------------
#
# `corpus/good/alias.wasm`. `bump` writes `$a` and returns `$b`; if the two
# indices were two cells it would answer 0, 0, 0 instead of 1, 2, 3. The two
# import entries must therefore become *one* field in the binding record.

alias_default=$(cat <<'EOF'
// Generated by script/sharing.sh. Do not edit.

///|
test "alias: unbound, the stand-in is still one cell" {
  inspect(bump(), content="1")
  inspect(peek(), content="1")
  inspect(bump(), content="2")
}
EOF
)

alias_bound=$(cat <<'EOF'
// Generated by script/sharing.sh. Do not edit.

///|
test "alias: bound, the host cell is the one the module reads" {
  moonlift_bind({ env_counter: Ref(5), env_base: Ref(0) })
  inspect(bump(), content="6")
  inspect(peek(), content="6")
}

///|
test "alias: writing the second index writes the first" {
  moonlift_bind({ env_counter: Ref(0), env_base: Ref(0) })
  inspect(poke(9), content="9")
  inspect(peek(), content="9")
}

///|
test "alias: a defined global takes the bound value at init" {
  moonlift_bind({ env_counter: Ref(0), env_base: Ref(7) })
  moonlift_init()
  inspect(copy(), content="7")
}
EOF
)

run_case "alias: unbound, two entries one cell" alias alias-default "$alias_default"
run_case "alias: bound, 3 properties" alias alias-bound "$alias_bound"

# One field, not two: the whole model in one grep on the generated source.
if grep -q '^  env_counter :' "$tmp/alias-bound/module.mbt" &&
  [ "$(grep -c 'env_counter :' "$tmp/alias-bound/module.mbt")" = "1" ]; then
  ok "alias: two import entries, one binding field" "env_counter"
else
  no "alias: two import entries, one binding field" "see module.mbt"
fi

# --- case 2: binding an instance, not pre-filling one ----------------------
#
# `corpus/good/imported.wasm` imports its memory, table and two globals, with a
# constant-offset data segment plus one placed at `global.get $base`. Handing it
# a fresh memory must still give `load0 = 'a'` and `loadbase = 'X'`: the segments
# are copied by instantiation, into whatever is bound.

imported_pre=$(cat <<'EOF'
// Generated by script/sharing.sh. Do not edit.

///|
test "imported: before init the bound memory is still empty" {
  moonlift_bind({
    env_tbl: Table::new(8),
    env_mem: Memory::new(1, 2),
    env_base: Ref(4),
    env_bump: Ref(0),
  })
  inspect(load0(), content="0")
}
EOF
)

imported_bound=$(cat <<'EOF'
// Generated by script/sharing.sh. Do not edit.

///|
test "imported: init copies the segments into the bound instance" {
  moonlift_bind({
    env_tbl: Table::new(8),
    env_mem: Memory::new(1, 2),
    env_base: Ref(4),
    env_bump: Ref(0),
  })
  moonlift_init()
  inspect(load0(), content="97")
  inspect(loadbase(), content="88")
  inspect(memsize(), content="1")
  inspect(viabase(0), content="10")
}

///|
test "imported: another base moves the segment and the slot together" {
  moonlift_bind({
    env_tbl: Table::new(8),
    env_mem: Memory::new(1, 2),
    env_base: Ref(2),
    env_bump: Ref(0),
  })
  moonlift_init()
  inspect(loadbase(), content="88")
  inspect(viabase(0), content="10")
}

///|
test "imported: the bound mutable global is written, not copied" {
  moonlift_bind({
    env_tbl: Table::new(8),
    env_mem: Memory::new(1, 2),
    env_base: Ref(4),
    env_bump: Ref(41),
  })
  moonlift_init()
  inspect(bump1(), content="42")
  inspect(bump1(), content="43")
}
EOF
)

run_case "imported: binding alone copies nothing" imported imported-pre "$imported_pre"
run_case "imported: bound memory, table, globals (3 properties)" imported imported-bound "$imported_bound"

printf 'sharing: %d ok, %d failed\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
