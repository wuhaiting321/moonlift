#!/usr/bin/env bash
# Differential verification: run the generated package against the original module.
#
#   bash script/verify.sh [-n calls-per-function] [fixture ...]
#
# For every fixture it
#   1. decompiles with `moonlift verify`, which also writes `calls.tsv` (the plan),
#   2. asks Node to run the *original* module for every planned call
#      (`corpus/tools/oracle.js --json`),
#   3. writes the expected values into a white-box test file inside the generated
#      package,
#   4. runs `moon test` on that package.
#
# What "matched" means: the same value, printed the same way. Integers compare as
# decimal text, floats as their bit patterns. A call where the original traps, or
# returns a NaN, is *skipped* and counted separately — a trap has no value to
# compare, and a NaN from arithmetic may legitimately differ in payload between
# two runtimes. A skipped call is not a pass, which is why it gets its own column.
set -uo pipefail

cd "$(dirname "$0")/.." || exit 1

per_func=16
fixtures=()
while [ $# -gt 0 ]; do
  case "$1" in
    -n) per_func="$2"; shift 2 ;;
    *) fixtures+=("$1"); shift ;;
  esac
done
if [ ${#fixtures[@]} -eq 0 ]; then
  for f in corpus/good/*.wasm; do fixtures+=("$f"); done
fi

tmp=/tmp/moonlift_verify
rm -rf "$tmp"
mkdir -p "$tmp"

cli() { moon run cmd/main --target "${TARGET:-wasm-gc}" -- "$@" 2>/dev/null; }

printf '%-16s %7s %7s %7s  %s\n' fixture calls matched skipped note
total=0
matched=0
skipped_all=0
bad=0

for f in "${fixtures[@]}"; do
  name=$(basename "$f" .wasm)
  dir="$tmp/$name"
  # A fixture whose reference implementation is exponential gets the bounded
  # pool. This is a statement about the *original*, not about the decompiler:
  # `fib` is recursive Fibonacci, so `fib(255)` never returns, and waiting for it
  # would say nothing about whether the generated code is right.
  flags=""
  case "$name" in
    fib) flags="--small" ;;
  esac
  cli verify "$f" -o "$dir" -n "$per_func" $flags > "$dir.plan" 2>&1
  if [ ! -f "$dir/calls.tsv" ]; then
    printf '%-16s %7s %7s %7s  %s\n' "$name" - - - "no plan (undecodable?)"
    bad=$((bad + 1))
    continue
  fi

  grep -v '^init' "$dir/calls.tsv" > "$dir/calls.body"
  n=$(grep -c . "$dir/calls.body" || true)
  if [ "$n" -eq 0 ]; then
    printf '%-16s %7s %7s %7s  %s\n' "$name" 0 - - "no exported function to call"
    continue
  fi

  # A call the original never finishes stops the sequence: the lines that did get
  # printed are still in order, so the ones before the hang are still comparable,
  # and the ones after it are reported as not compared rather than as passes.
  timeout "${ORACLE_TIMEOUT:-30}" node corpus/tools/oracle.js --json "$f" "$dir/calls.tsv" \
    > "$dir/oracle.tsv" 2>"$dir/oracle.err"
  cut=no
  if [ "$(grep -c . "$dir/oracle.tsv" || true)" -lt "$n" ]; then
    cut=yes
  fi
  if head -1 "$dir/oracle.tsv" | grep -q '^error'; then
    printf '%-16s %7s %7s %7s  %s\n' "$name" "$n" - - \
      "the original needs a host: $(head -1 "$dir/oracle.tsv" | cut -f4)"
    skipped_all=$((skipped_all + n))
    continue
  fi

  init=0
  grep -q '^init' "$dir/calls.tsv" && init=1

  paste "$dir/calls.body" "$dir/oracle.tsv" | awk -F'\t' -v init="$init" '
    function close_block() {
      if (body != "") {
        printf "\n///|\ntest \"verify %s\" {\n", last
        if (init == 1) print "  moonlift_init()"
        printf "%s", body
        print "}"
      }
      body = ""
    }
    {
      call = $1 "(" $4 ")"
      if ($6 != "ok") {
        skipped[$1] = skipped[$1] " " $4 " (" $6 ")"
        next
      }
      if ($3 == "f32") expr = call ".reinterpret_as_int().to_string()"
      else if ($3 == "f64") expr = call ".reinterpret_as_int64().to_string()"
      else expr = call ".to_string()"
      if ($1 != last) {
        close_block()
        last = $1
      }
      body = body "  inspect(" expr ", content=\"" $9 "\")\n"
    }
    END {
      close_block()
      for (k in skipped) printf "// skipped %s:%s\n", k, skipped[k]
    }
  ' > "$dir/oracle_wbtest.mbt"

  {
    echo "// Generated by script/verify.sh. Do not edit."
    echo "//"
    echo "// Every expected value below came from running the *original* module in Node"
    echo "// (corpus/tools/oracle.js), so each line compares two implementations."
    echo "//"
    echo "// Integers compare as decimal text, floats as their bit patterns. Calls whose"
    echo "// original traps, or returns a NaN, are listed as comments, not asserted."
  } > "$dir/head.mbt"
  cat "$dir/head.mbt" "$dir/oracle_wbtest.mbt" > "$dir/final.mbt"
  mv "$dir/final.mbt" "$dir/oracle_wbtest.mbt"
  rm -f "$dir/head.mbt"

  compared=$(grep -c '^  inspect(' "$dir/oracle_wbtest.mbt" || true)
  dropped=$(grep -c '^// skipped' "$dir/oracle_wbtest.mbt" || true)

  if [ "$compared" -eq 0 ]; then
    printf '%-16s %7s %7s %7s  %s\n' "$name" 0 - "$dropped" \
      "every planned call traps in the original"
    skipped_all=$((skipped_all + n))
    continue
  fi

  note="-"
  if [ "$cut" = yes ]; then
    note="the original did not finish; $(grep -c . "$dir/oracle.tsv") of $n compared"
  fi

  if ( cd "$dir" && timeout "${TEST_TIMEOUT:-300}" moon test --target "${TARGET:-wasm-gc}" > "$dir/test.log" 2>&1 ); then
    printf '%-16s %7d %7d %7d  %s\n' "$name" "$compared" "$compared" \
      $((n - compared)) "$note"
    total=$((total + compared))
    matched=$((matched + compared))
    skipped_all=$((skipped_all + n - compared))
  else
    printf '%-16s %7d %7d %7d  %s\n' "$name" "$compared" 0 $((n - compared)) \
      "see $dir/test.log"
    grep -E '^(Error|expect|Total tests|.*FAILED)' "$dir/test.log" | head -4 |
      sed 's/^/                 /'
    total=$((total + compared))
    bad=$((bad + compared))
    skipped_all=$((skipped_all + n - compared))
  fi
done

printf '\n%-16s %7d %7d %7d\n' TOTAL "$total" "$matched" "$skipped_all"
printf 'calls compared: %d, matched: %d, skipped (trap/NaN): %d, failed: %d\n' \
  "$total" "$matched" "$skipped_all" "$bad"

if [ "$total" -eq 0 ]; then
  echo "verify: nothing was compared"
  exit 1
fi
if [ "$bad" -ne 0 ]; then
  echo "verify: FAILED"
  exit 1
fi
echo "verify: every compared call matched the original"
