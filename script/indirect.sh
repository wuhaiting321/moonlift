#!/usr/bin/env bash
# Trap parity for indirect calls.
#
#   bash script/indirect.sh [fixture ...]
#
# `verify.sh` compares values and counts a call whose original traps as
# "skipped". For a direct call that is the right call — a trap has no value to
# compare. For `call_indirect` it leaves the interesting half untested, because
# three of its four outcomes *are* traps:
#
#   the index is outside the table              -> trap
#   the slot was never initialised              -> trap
#   the function there has another signature    -> trap
#   otherwise the call returns a value
#
# So this script runs every planned call on both sides, one process per call
# (a trap ends the process), and compares:
#
#   value vs value   the same rendering rule as verify.sh
#   trap  vs trap    a non-zero exit on both sides
#
# A trap match is only accepted when the trap is the *right* one: when Node's
# message comes from the table ("out of bounds", "uninitialized", "signature
# mismatch"), the generated side must name `call_indirect` in its message. A
# crash from an unrelated bug therefore cannot be counted as a pass.
#
# That message is printed by the probe build only. MoonBit's `abort` drops its
# argument on every backend, so the probe copy of `runtime.mbt` prints before
# aborting; the shipped runtime is untouched and `verify.sh` never sees this.
set -uo pipefail

cd "$(dirname "$0")/.." || exit 1

fixtures=("$@")
if [ ${#fixtures[@]} -eq 0 ]; then
  fixtures=(corpus/good/indirect.wasm corpus/good/table.wasm)
fi

tmp=/tmp/moonlift_indirect
rm -rf "$tmp"
mkdir -p "$tmp"

cli() { moon run cmd/main --target "${TARGET:-wasm-gc}" -- "$@" 2>/dev/null; }

printf '%-12s %6s %6s %6s %6s  %s\n' fixture cases value trap failed note
grand_total=0
grand_fail=0

for f in "${fixtures[@]}"; do
  name=$(basename "$f" .wasm)
  dir="$tmp/$name"
  cli verify "$f" -o "$dir" -n 16 > "$dir.plan" 2>&1
  if [ ! -f "$dir/calls.tsv" ]; then
    printf '%-12s %6s %6s %6s %6s  %s\n' "$name" - - - - "no plan"
    grand_fail=$((grand_fail + 1))
    continue
  fi
  # `init` and `host` are directives, not calls; match the whole first field so
  # that an export called `hostcall` is not filtered out by a prefix rule.
  awk -F'\t' '$1 != "init" && $1 != "host"' "$dir/calls.tsv" > "$dir/calls.body"
  n=$(grep -c . "$dir/calls.body" || true)
  if [ "$n" -eq 0 ]; then
    printf '%-12s %6s %6s %6s %6s  %s\n' "$name" 0 - - - "no calls"
    continue
  fi

  node corpus/tools/oracle.js --json "$f" "$dir/calls.tsv" \
    > "$dir/oracle.tsv" 2> "$dir/oracle.err"
  if head -1 "$dir/oracle.tsv" | grep -q '^error'; then
    printf '%-12s %6s %6s %6s %6s  %s\n' "$name" "$n" - - - \
      "the original needs a host: $(head -1 "$dir/oracle.tsv" | cut -f4)"
    grand_fail=$((grand_fail + 1))
    continue
  fi

  # --- the probe build -----------------------------------------------------
  # One `match` arm per planned call. A value arm prints; a trap arm calls and
  # never returns.
  paste "$dir/calls.body" "$dir/oracle.tsv" | awk -F'\t' '
    BEGIN {
      print "// Generated by script/indirect.sh. Do not edit."
      print "//"
      print "// One arm per planned call, so a trap stops exactly one case."
      print ""
      print "fn num(s : String) -> Int {"
      print "  let mut n = 0"
      print "  for c in s {"
      print "    n = n * 10 + (c.to_int() - 48)"
      print "  }"
      print "  n"
      print "}"
      print ""
      print "fn probe(k : Int) -> Unit {"
      print "  match k {"
    }
    {
      i = NR - 1
      call = $1 "(" $4 ")"
      if ($6 == "ok") {
        if ($3 == "f32") conv = ".reinterpret_as_int().to_string()"
        else if ($3 == "f64") conv = ".reinterpret_as_int64().to_string()"
        else conv = ".to_string()"
        printf "    %d => println(%s%s)\n", i, call, conv
      } else if ($6 == "trap") {
        printf "    %d => ignore(%s)\n", i, call
      } else {
        printf "    %d => println(\"matched-nothing\")\n", i
      }
    }
    END {
      print "    _ => trap(\"no such case\")"
      print "  }"
      print "}"
    }
  ' > "$dir/probe.mbt"

  cat > "$dir/moon.pkg" <<'EOF'
// Probe build: makes the generated package runnable, one call per process.
import {
  "moonbitlang/core/env",
}
pkgtype(kind: "executable")
EOF

  if grep -q '^init' "$dir/calls.tsv"; then
    init_call="moonlift_init()"
  else
    init_call=""
  fi
  cat >> "$dir/probe.mbt" <<EOF

///|
fn main {
  let a = @env.args()
  ${init_call}
  probe(num(a[a.length() - 1]))
}
EOF

  # Print the trap message before aborting. Harness only — see the header.
  python - "$dir/runtime.mbt" <<'PY'
import io, sys
p = sys.argv[1]
s = io.open(p, encoding="utf-8").read()
old = 'abort("moonlift: " + msg)'
new = 'println("moonlift: " + msg)\n  abort("moonlift: " + msg)'
if old not in s:
    sys.exit("probe: runtime.mbt has no trap body to instrument")
io.open(p, "w", encoding="utf-8").write(s.replace(old, new, 1))
PY

  if ! ( cd "$dir" && moon build --target wasm-gc > "$dir/build.log" 2>&1 ); then
    printf '%-12s %6s %6s %6s %6s  %s\n' "$name" "$n" - - - "probe does not build"
    tail -5 "$dir/build.log" | sed 's/^/             /'
    grand_fail=$((grand_fail + 1))
    continue
  fi

  # --- run every case ------------------------------------------------------
  value=0
  trap=0
  failed=0

  k=0
  while [ "$k" -lt "$n" ]; do
    oracle_line=$(sed -n "$((k + 1))p" "$dir/oracle.tsv")
    if [ -z "$oracle_line" ]; then
      printf '     case %d: the original never answered\n' "$k"
      failed=$((failed + 1))
      k=$((k + 1))
      continue
    fi
    st=$(printf '%s' "$oracle_line" | cut -f1)
    why=$(printf '%s' "$oracle_line" | cut -f4)
    out=$( cd "$dir" && timeout 30 moon run . --target wasm-gc -- "$k" 2>/dev/null )
    code=$?
    if [ "$code" -eq 124 ]; then
      printf '     case %d: the generated side did not finish in 30s\n' "$k"
      failed=$((failed + 1))
      k=$((k + 1))
      continue
    fi
    if [ "$st" = "ok" ]; then
      if [ "$code" -ne 0 ]; then
        printf '     case %d: value expected, the generated side trapped\n' "$k"
        printf '       original: %s\n' "$why"
        failed=$((failed + 1))
      elif [ "$out" != "$why" ]; then
        printf '     case %d: %s != %s (generated vs original)\n' "$k" "$out" "$why"
        failed=$((failed + 1))
      else
        value=$((value + 1))
      fi
    elif [ "$st" = "trap" ]; then
      if [ "$code" -eq 0 ]; then
        printf '     case %d: the original trapped (%s), the generated side returned %s\n' \
          "$k" "$why" "$out"
        failed=$((failed + 1))
      else
        case "$why" in
          *table* | *signature* | *uninitialized* | *uninitialised*)
            if printf '%s' "$out" | grep -q 'call_indirect'; then
              trap=$((trap + 1))
            else
              printf '     case %d: trapped, but not in the dispatcher: %s\n' "$k" "$out"
              failed=$((failed + 1))
            fi
            ;;
          *)
            # A trap that is not about the table (a division, say): parity of
            # "both trapped" is all that can be compared.
            trap=$((trap + 1))
            ;;
        esac
      fi
    else
      # nan: the payload may legitimately differ between two runtimes.
      :
    fi
    k=$((k + 1))
  done

  note="-"
  if grep -q '^trap' "$dir/oracle.tsv"; then
    note="$(grep '^trap' "$dir/oracle.tsv" | cut -f4 | sort -u | paste -sd ';' -)"
  fi
  printf '%-12s %6d %6d %6d %6d  %s\n' "$name" "$n" "$value" "$trap" "$failed" \
    "$note"
  grand_total=$((grand_total + n))
  grand_fail=$((grand_fail + failed))
done

printf '\n%-12s %6d %6s %6s %6d\n' TOTAL "$grand_total" - - "$grand_fail"
if [ "$grand_fail" -ne 0 ]; then
  echo "indirect: FAILED"
  exit 1
fi
echo "indirect: every case matched — values equal, traps in the dispatcher"
